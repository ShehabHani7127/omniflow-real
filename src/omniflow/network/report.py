"""Write the human-readable M1 reports: a network summary and a field checklist.

Every number in these files is computed from the network and the snapshot by
code, so the reports can be regenerated at any time and never drift from the
data. Nothing in them is typed in by hand.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

import sumolib

from omniflow.network.area import BoundingBox
from omniflow.network.build import BuildReport, LoadCheck
from omniflow.network.inventory import ExpectedMatch, SignalRecord

MPH_PER_MS = 2.23694

GENERATED_NOTE = (
    "*Generated by `scripts/m1_build_network.py`. Do not edit by hand: rerun the script.*"
)


def checks_for_the_field(records: list[SignalRecord]) -> list[str]:
    """List the network features that most need checking on the street.

    The rules are mechanical, so they find the same things every time:

    * a signal where the network allows no turns at all (a turn ban, or an
      OSM mistake);
    * a signal with only three approaches (a T-intersection in the network:
      is the fourth leg really missing, or only a driveway?);
    * a signal with exactly one incoming lane per approach (are there really
      no turn lanes?).
    """
    notes = []
    for r in records:
        if r.left == 0 and r.right == 0:
            notes.append(
                f"#{r.signal_no} {r.name}: the network allows **no turns**, only "
                f"{r.straight} straight-through movements. Are all turns really banned?"
            )
        if r.approaches == 3:
            notes.append(
                f"#{r.signal_no} {r.name}: only **3 approaches** in the network. Is the "
                "fourth leg missing, or is it a driveway or campus road?"
            )
        if r.incoming_lanes == r.approaches:
            notes.append(
                f"#{r.signal_no} {r.name}: **one lane per approach** in the network. "
                "Are there really no separate turn lanes?"
            )
    return notes


def render_summary(
    *,
    snapshot_name: str,
    snapshot_meta: dict[str, object],
    bbox: BoundingBox,
    net_file: Path,
    build: BuildReport,
    load: LoadCheck,
    records: list[SignalRecord],
    matches: list[ExpectedMatch],
    sumo_version: str,
) -> str:
    """Return the Markdown text of the M1 network summary.

    Args:
        snapshot_name: Repository-relative path of the OSM snapshot.
        snapshot_meta: The snapshot's provenance record.
        bbox: The study area.
        net_file: The built network.
        build: What happened during the build.
        load: Result of the SUMO load check.
        records: The signal inventory.
        matches: The comparison with the outside list of signals.
        sumo_version: Version of the SUMO that built the network.
    """
    net = sumolib.net.readNet(str(net_file))
    edges = net.getEdges()
    xmin, ymin, xmax, ymax = net.getBoundary()
    road_km = sum(e.getLength() for e in edges) / 1000
    lane_km = sum(e.getLength() * e.getLaneNumber() for e in edges) / 1000
    speeds = Counter(round(e.getSpeed() * MPH_PER_MS) for e in edges)
    found = sum(m.signal is not None for m in matches)

    lines = [
        "# M1 network summary",
        "",
        GENERATED_NOTE,
        "",
        "## Inputs",
        "",
        "| Item | Value |",
        "|------|-------|",
        f"| OpenStreetMap snapshot | `{snapshot_name}` |",
        f"| Downloaded (UTC) | {snapshot_meta['downloaded_at_utc']} |",
        f"| Source | {snapshot_meta['source_url']} |",
        f"| SHA-256 (uncompressed) | `{snapshot_meta['sha256_uncompressed']}` |",
        f"| Map points / ways / relations | {snapshot_meta['nodes']} / {snapshot_meta['ways']} / "
        f"{snapshot_meta['relations']} |",
        f"| Study area (west, south, east, north) | {bbox.as_lon_lat_string()} |",
        f"| SUMO version | {sumo_version} |",
        "",
        "Map data © OpenStreetMap contributors, available under the Open Database License.",
        "",
        "## Network",
        "",
        "| Item | Value |",
        "|------|-------|",
        f"| Extent | {xmax - xmin:.0f} m east-west by {ymax - ymin:.0f} m north-south |",
        f"| Road edges (one per direction) | {len(edges)} |",
        f"| Total edge length | {road_km:.1f} km |",
        f"| Total lane length | {lane_km:.1f} km |",
        f"| Junctions | {len(net.getNodes())} |",
        f"| Signalized intersections | {len(records)} |",
        "",
        "Speed limits on the network's edges:",
        "",
        "| Speed limit | Edges |",
        "|-------------|-------|",
        *(f"| {mph} mph | {count} |" for mph, count in sorted(speeds.items())),
        "",
        "Roads without a `maxspeed` tag in OSM get 30 mph (Florida Statutes 316.183(2), "
        "see `network/config/florida_speed_defaults.typ.xml`).",
        "",
        "## Build checks",
        "",
    ]
    if build.clip is not None:
        c = build.clip
        lines += [
            f"* **Clipping to the study area** kept {c.nodes_kept} map points and removed "
            f"{c.nodes_removed}. {c.roads_shortened} roads were cut back at the edge, "
            f"{c.roads_removed} roads were removed (fewer than two points inside), and "
            f"{c.roads_split} roads left the area and came back in.",
        ]
    lines += [
        f"* **Patches applied:** {len(build.patches)}"
        + (f" ({', '.join(p.name for p in build.patches)})" if build.patches else "")
        + ".",
        f"* **SUMO load check:** the network was loaded and simulated empty for "
        f"{load.seconds_simulated} s with {len(load.warnings)} warnings and no errors.",
        f"* **netconvert warnings:** {build.warning_count} in total, by kind:",
        "",
        "| Count | Kind of warning |",
        "|-------|-----------------|",
        *(
            f"| {count} | {kind.removeprefix('Warning: ').replace('|', '/')} |"
            for kind, count in build.warning_kinds().most_common()
        ),
        "",
        "What the warning kinds mean is explained in `LEARNING.md` (milestone M1).",
        "",
        "## Signalized intersections",
        "",
        "Turning movements are lane-to-lane links (s = straight, l = left, r = right). "
        "Cycle lengths are netconvert's placeholder programs; realistic timings come in M3.",
        "",
        "| # | Intersection | Approaches | Incoming lanes | s / l / r | Latitude | Longitude |",
        "|---|--------------|------------|----------------|-----------|----------|-----------|",
        *(
            f"| {r.signal_no} | {r.name} | {r.approaches} | {r.incoming_lanes} | "
            f"{r.straight} / {r.left} / {r.right} | {r.lat:.5f} | {r.lon:.5f} |"
            for r in records
        ),
        "",
        "## Comparison with the FDOT list of signals on Woodland Blvd",
        "",
        f"{found} of {len(matches)} intersections named by the outside source are signalized "
        "in the network.",
        "",
        "| Intersection named by the source | In the network |",
        "|----------------------------------|----------------|",
        *(
            f"| {m.expected.street_a} & {m.expected.street_b} | "
            + (f"yes, #{m.signal.signal_no}" if m.signal else "**no**")
            + " |"
            for m in matches
        ),
        "",
        f"Source: {matches[0].expected.source}." if matches else "",
        "",
        "## Things to check in the field",
        "",
        *(f"* {note}" for note in checks_for_the_field(records)),
        "",
        "The full per-signal checklist is in `field_checklist.md`.",
        "",
    ]
    return "\n".join(lines)


def render_field_checklist(records: list[SignalRecord]) -> str:
    """Return a printable Markdown checklist for a walk along the corridor."""
    lines = [
        "# Field checklist: signalized intersections",
        "",
        GENERATED_NOTE,
        "",
        "Take this on a walk (or print it). For each intersection, compare the street "
        "with what the digital twin assumes. Write down what is different, with the date "
        "and a photo if you can. Corrections go into `network/patches/` (see the README "
        "there), never into the network file itself.",
        "",
        "Safety first: stay on the sidewalk, do not stand in the road to take photos.",
        "",
    ]
    for r in records:
        osm_link = f"https://www.openstreetmap.org/?mlat={r.lat:.5f}&mlon={r.lon:.5f}#map=19/{r.lat:.5f}/{r.lon:.5f}"
        lines += [
            f"## {r.signal_no}. {r.name}",
            "",
            f"Location: {r.lat:.5f}, {r.lon:.5f} ([map]({osm_link})). Streets: {r.streets}.",
            "",
            "| What the network assumes | Matches the street? | Notes |",
            "|--------------------------|---------------------|-------|",
            "| A working traffic signal | [ ] yes [ ] no | |",
            f"| {r.approaches} approaches (roads leading in) | [ ] yes [ ] no | |",
            f"| {r.incoming_lanes} incoming lanes in total | [ ] yes [ ] no | |",
            f"| Movements: {r.straight} straight, {r.left} left, {r.right} right | "
            "[ ] yes [ ] no | |",
            "| Turn bans / one-way streets as in the network | [ ] yes [ ] no | |",
            "| Speed limit signs on the approaches | | write them down |",
            "",
        ]
    return "\n".join(lines)
